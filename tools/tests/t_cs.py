from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--autoplay-policy=no-user-gesture-required'])
    pg = b.new_page(viewport={'width': 400, 'height': 820}, device_scale_factor=2, has_touch=True, is_mobile=True)
    errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('console', lambda m: m.type == 'error' and errs.append(m.text))
    pg.goto('http://localhost:8765/?seed=3')
    pg.wait_for_timeout(2500)
    pg.click('#btn-checkin-back'); pg.wait_for_timeout(600)
    pg.screenshot(path='/tmp/cs_title.png')
    pg.click('#btn-char'); pg.wait_for_timeout(1200)
    pg.screenshot(path='/tmp/cs_gato.png')
    pg.click('#cs-next'); pg.wait_for_timeout(900)
    pg.screenshot(path='/tmp/cs_guax.png')
    for i in range(3): pg.click('#cs-next'); pg.wait_for_timeout(300)
    pg.wait_for_timeout(700)
    pg.screenshot(path='/tmp/cs_coelho.png')
    pg.evaluate("__game.meta.cyberCoins = 500")
    pg.click('.cs-pip:nth-child(2)'); pg.wait_for_timeout(400)
    pg.click('#cs-action'); pg.wait_for_timeout(500)
    print('sel', pg.evaluate("__game.meta.selected"), pg.inner_text('#cs-action'))
    pg.click('#cs-back'); pg.wait_for_timeout(600)
    print('chip', pg.inner_text('#chip-name'), 'sheets', pg.evaluate("Object.keys(__R.sheets)"))
    pg.screenshot(path='/tmp/cs_title2.png')
    pg.click('#btn-char'); pg.wait_for_timeout(300); pg.click('#cs-action'); pg.wait_for_timeout(2500)
    print('state', pg.evaluate("__game.state"), pg.evaluate("__game.mode"), 'sheets', pg.evaluate("Object.keys(__R.sheets)"))
    print('errors', errs)
    b.close()
